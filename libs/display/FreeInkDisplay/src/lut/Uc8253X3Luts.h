// DC-balance gate (UltraChipLutBalance.h; UC8253 uses the UC8179 row layout).
// Holds of _normal and _fast are GND (stock/community pushed WW -1/-2 and BB
// +1/+2 every page). The scrub runs the _full WW row for every white target and
// the _full BB row for every black one, so each row nets zero whatever DTM1
// holds. Vendor exemptions (gray, pending the AA decision): _gc nets WW -2, BW -3;
// _aa_pre_bw_mid nets WW -4, BW -27, WB +26, BB +5.
constexpr lutbalance::LutSet x3Set(const uint8_t* vcom, const uint8_t* ww, const uint8_t* bw, const uint8_t* wb,
                                   const uint8_t* bb) {
  const uint8_t* rows[lutbalance::kRows] = {vcom, ww, bw, wb, bb};
  lutbalance::LutSet s{};
  for (size_t r = 0; r < lutbalance::kRows; ++r)
    for (size_t i = 0; i < lutbalance::kRowBytes; ++i) s.row[r][i] = rows[r][i];
  return s;
}
static_assert(lutbalance::balanced(x3Set(lut_x3_vcom_normal, lut_x3_ww_normal, lut_x3_bw_normal, lut_x3_wb_normal,
                                         lut_x3_bb_normal),
                                   lutbalance::Policy::Transition),
              "X3 _normal not DC balanced");
static_assert(lutbalance::balanced(x3Set(lut_x3_vcom_fast, lut_x3_ww_fast, lut_x3_bw_fast, lut_x3_wb_fast, lut_x3_bb_fast),
                                   lutbalance::Policy::Transition),
              "X3 _fast not DC balanced");
static_assert(lutbalance::balanced(x3Set(lut_x3_vcom_full, lut_x3_ww_full, lut_x3_bw_full, lut_x3_wb_full, lut_x3_bb_full),
                                   lutbalance::Policy::Transition),
              "X3 _full not DC balanced");
static_assert(lutbalance::balanced(x3Set(lut_x3_vcom_full, lut_x3_ww_full, lut_x3_ww_full, lut_x3_bb_full, lut_x3_bb_full),
                                   lutbalance::Policy::Absolute),
              "X3 scrub not DC balanced");

