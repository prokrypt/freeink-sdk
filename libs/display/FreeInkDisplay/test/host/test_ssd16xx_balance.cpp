// Compile-only check of the SSD16xx LUT DC-balance rule:
//   c++ -std=c++17 -fsyntax-only -I src test/host/test_ssd16xx_balance.cpp
#include "lut/Ssd16xxLutBalance.h"

using freeink::ssd16xxbalance::balanced;

namespace {

// Stock X4 AA waveform (light +7, gray -9, dark -6 frames per page).
constexpr unsigned char kStockAa[110] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x54, 0x54, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0xAA, 0xA0, 0xA8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0xA2, 0x22, 0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x01, 0x01, 0x01, 0x01, 0x00, 0x01, 0x01, 0x01, 0x01, 0x00,  //
    0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  //
    0x8F, 0x8F, 0x8F, 0x8F, 0x8F, 0x17, 0x41, 0xA8, 0x32, 0x30};
static_assert(!balanced(kStockAa), "stock AA rows push one way");

struct Lut {
  unsigned char b[110];
};
constexpr Lut pair(unsigned char levels, unsigned char rp, unsigned char vsh1Code, unsigned char vslCode) {
  Lut l{};
  l.b[10] = levels;  // LUT1, group 0
  l.b[50] = 2;       // TP_A
  l.b[51] = 2;       // TP_B
  l.b[54] = rp;
  l.b[106] = vsh1Code;
  l.b[108] = vslCode;
  return l;
}
constexpr Lut kPair = pair(0x60, 1, 0x41, 0x32);   // A VSH1, B VSL
constexpr Lut kOneWay = pair(0x40, 0, 0x41, 0x32);  // A VSH1 only
constexpr Lut kVsh2 = pair(0xE0, 0, 0x41, 0x32);    // A VSH2
constexpr Lut kLowVsh1 = pair(0x60, 0, 0x23, 0x32); // VSH1 9 V vs VSL -15 V
static_assert(balanced(kPair.b), "VSH1 2 + VSL 2 balances");
static_assert(!balanced(kOneWay.b), "a lone VSH1 push is one-way");
static_assert(!balanced(kVsh2.b), "VSH2 is not modeled");
static_assert(!balanced(kLowVsh1.b), "unequal rails break frame-count balance");

}  // namespace

int main() { return 0; }
